package dev.pocket.opencode.core

import android.content.Context
import android.net.ConnectivityManager
import android.net.Network
import android.net.NetworkCapabilities
import java.io.File
import java.net.InetAddress
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import okhttp3.Request

/**
 * 网络相关杂活：把 Android 的 DNS 写进 rootfs 的 /etc/resolv.conf。
 *
 * Android 没有 /etc/resolv.conf，容器里的 glibc 解析域名会失败，
 * 所以每次安装/启动前都要从 ConnectivityManager 读当前 DNS 再写进容器。
 */
class NetworkBridge(private val context: Context, private val paths: PocketPaths, private val downloader: Downloader) {

    private val connectivity: ConnectivityManager? =
        context.getSystemService(Context.CONNECTIVITY_SERVICE) as? ConnectivityManager

    /** 当前网络的首选 DNS 服务器（IPv4 优先，去掉 link-local 的 %scope 后缀）。 */
    fun currentDnsServers(): List<String> {
        val result = LinkedHashSet<String>()
        try {
            val manager = connectivity ?: return fallbackDns()
            val active: Network? = manager.activeNetwork
            val properties = active?.let { manager.getLinkProperties(it) }
            val servers = properties?.dnsServers?.mapNotNull { address ->
                address.hostAddress?.substringBefore('%')?.takeIf { it.isNotBlank() }
            }
            if (servers != null) result += servers
            if (result.isEmpty()) {
                manager.allNetworks.forEach { network ->
                    manager.getLinkProperties(network)?.dnsServers?.forEach { address ->
                        address.hostAddress?.substringBefore('%')?.takeIf { it.isNotBlank() }?.let { result += it }
                    }
                }
            }
        } catch (_: Exception) {
        }
        if (result.isEmpty()) result += fallbackDns()
        // 私人 DNS（DoT）开启时上报的服务器可能不可直连，公共 DNS 作为兜底附在后面
        result += fallbackDns()
        // 容器里没有 IPv6 路由时优先 IPv4
        return result.distinct().sortedBy { if (it.contains(':')) 1 else 0 }
    }

    private fun fallbackDns(): List<String> = listOf("223.5.5.5", "119.29.29.29", "1.1.1.1")

    fun isOnline(): Boolean {
        val manager = connectivity ?: return true
        val network = manager.activeNetwork ?: return false
        val capabilities = manager.getNetworkCapabilities(network) ?: return false
        return capabilities.hasCapability(NetworkCapabilities.NET_CAPABILITY_INTERNET)
    }

    /** 把 DNS 写进 rootfs。调用前 rootfs 必须已存在。 */
    suspend fun writeResolvConf() = withContext(Dispatchers.IO) {
        val target = File(paths.rootfs, "etc/resolv.conf")
        if (!target.parentFile.isDirectory) return@withContext
        // 上游 rootfs 里 /etc/resolv.conf 可能是软链（如指向 systemd-resolved），写了会跑出树外
        FileOps.ensureNoSymlinkPath(paths.rootfs, target)
        val lines = buildString {
            appendLine("# generated by OpenCode Pocket")
            currentDnsServers().forEach { appendLine("nameserver $it") }
            appendLine("options timeout:2 attempts:2")
        }
        target.writeText(lines)
    }

    /** 记录 DNS 注入的次数，便于诊断。 */
    suspend fun ping(host: String = "mirrors.tuna.tsinghua.edu.cn", timeoutMs: Long = 2500): Long? =
        withContext(Dispatchers.IO) {
            try {
                val client = downloader.http.newBuilder()
                    .callTimeout(timeoutMs, java.util.concurrent.TimeUnit.MILLISECONDS)
                    .build()
                val request = Request.Builder().url("https://$host/").head().build()
                val start = System.currentTimeMillis()
                client.newCall(request).execute().use {
                    System.currentTimeMillis() - start
                }
            } catch (_: Exception) {
                null
            }
        }

    /** 简单的延迟测试（HTTP HEAD，失败返回 null）。 */
    suspend fun latencyOf(url: String, timeoutMs: Long = 4000): Long? = withContext(Dispatchers.IO) {
        try {
            val client = downloader.http.newBuilder()
                .callTimeout(timeoutMs, java.util.concurrent.TimeUnit.MILLISECONDS)
                .build()
            val start = System.currentTimeMillis()
            client.newCall(Request.Builder().url(url).head().build()).execute().use { }
            System.currentTimeMillis() - start
        } catch (_: Exception) {
            null
        }
    }
}
